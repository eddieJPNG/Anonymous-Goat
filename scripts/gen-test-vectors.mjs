#!/usr/bin/env node
// Regenerates contracts/verifier/src/test_vectors.rs from the artifacts of the
// current ceremony output.
//
// `vote` verifies against the VK embedded in src/vk.rs by `ctg zk build main
// --embed-vk`, so the vectors only make sense for the same key pair. Always run
// this right after a build + prove cycle:
//
//   npx ctg zk build main --embed-vk
//   npx ctg zk prove main
//   node scripts/gen-test-vectors.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const ARTIFACTS = join(ROOT_DIR, ".artifacts", "zk", "main");
const OUT = join(ROOT_DIR, "contracts", "verifier", "src", "test_vectors.rs");

const proof = JSON.parse(readFileSync(join(ARTIFACTS, "proof.json"), "utf8"));
// snarkjs order: [nullifier, merkleRoot, electionId, vote].
const [nullifier, merkleRoot, electionId, vote] = JSON.parse(
  readFileSync(join(ARTIFACTS, "public.json"), "utf8")
);

// snarkjs and Caatinga label the curve "bls12381" in proof.json.
if (proof.curve !== "bls12381") {
  throw new Error(`expected bls12381 proof, got ${proof.curve}`);
}

/** Field element (decimal string) -> 0x-prefixed 32-byte big-endian hex. */
function toHex32(decimal) {
  return `0x${BigInt(decimal).toString(16).padStart(64, "0")}`;
}

// snarkjs prints G1 as [x, y, z] and each G2 coordinate as [c0, c1] in decimal.
const [aX, aY] = proof.pi_a;
const [[bX0, bX1], [bY0, bY1]] = proof.pi_b;
const [cX, cY] = proof.pi_c;

const body = `// AUTO-GENERATED by scripts/gen-test-vectors.mjs — do not edit.
//
// Proof and public signals produced by the same ceremony output as src/vk.rs.
// Regenerate after every \`npx ctg zk build main --embed-vk\` + \`npx ctg zk prove
// main\`, otherwise \`cargo test\` verifies against a stale key.
#![cfg(test)]

pub const PROOF_A_X: &str = "${aX}";
pub const PROOF_A_Y: &str = "${aY}";
pub const PROOF_B_X0: &str = "${bX0}";
pub const PROOF_B_X1: &str = "${bX1}";
pub const PROOF_B_Y0: &str = "${bY0}";
pub const PROOF_B_Y1: &str = "${bY1}";
pub const PROOF_C_X: &str = "${cX}";
pub const PROOF_C_Y: &str = "${cY}";

pub const NULLIFIER_HEX: &str = "${toHex32(nullifier)}";
pub const MERKLE_ROOT_HEX: &str = "${toHex32(merkleRoot)}";
pub const ELECTION_ID_HEX: &str = "${toHex32(electionId)}";
pub const VOTE: u32 = ${Number(vote)};
`;

writeFileSync(OUT, body);
console.log(`wrote ${OUT}`);
console.log(`vote: ${vote}  nullifier: ${toHex32(nullifier)}`);
