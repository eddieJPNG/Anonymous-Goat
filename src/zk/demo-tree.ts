import demoTreeJson from "../../circuits/demo-tree.json";

/**
 * One demo elector: the secret and the Merkle path the browser turns into the
 * snarkjs `input.json`. Secrets here are demo-only values derived from a fixed
 * seed — real voter secrets are distributed off-chain and never committed.
 */
export interface DemoVoter {
  index: number;
  secret: string;
  merklePath: string[];
  merkleIndices: string[];
}

interface DemoTreeDocument {
  depth: number;
  numVoters: number;
  electionId: string;
  merkleRoot: string;
  electionIdHex: string;
  merkleRootHex: string;
  voters: DemoVoter[];
}

const document = demoTreeJson as DemoTreeDocument;

/**
 * Demo eligibility tree, generated by `node scripts/gen-demo-tree.mjs`.
 * `merkleRoot` / `electionId` are decimal field elements (snarkjs input
 * format); the `…Hex` variants are the big-endian `BytesN<32>` encodings the
 * contract compares against.
 */
export const demoTree = {
  depth: document.depth,
  electionId: document.electionId,
  merkleRoot: document.merkleRoot,
  electionIdHex: document.electionIdHex,
  merkleRootHex: document.merkleRootHex,
  voters: document.voters,
};

export function demoVoter(index: number): DemoVoter {
  const voter = document.voters[index];
  if (!voter) {
    throw new Error(`Unknown demo voter ${index}. Regenerate with \`node scripts/gen-demo-tree.mjs\`.`);
  }
  return voter;
}
